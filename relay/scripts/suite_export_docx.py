
import json
import sys
import base64
from io import BytesIO
from datetime import datetime
from docx import Document
from docx.shared import Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

# Severity colors from PaperHawk
COLOR_HIGH = RGBColor(0xCC, 0x00, 0x00)
COLOR_MEDIUM = RGBColor(0xCC, 0x88, 0x00)
COLOR_LOW = RGBColor(0x00, 0x33, 0x99)
COLOR_INFO = RGBColor(0x66, 0x66, 0x66)

def get_color(severity):
    return {
        "critical": COLOR_HIGH,
        "high": COLOR_HIGH,
        "medium": COLOR_MEDIUM,
        "low": COLOR_LOW,
        "suggestion": COLOR_INFO,
    }.get(severity.lower(), COLOR_INFO)

def build_docx(data):
    text = data.get("text", "")
    audit = data.get("audit", {})
    
    doc = Document()
    
    # 1. Title
    title = doc.add_heading("Suite AI Document Audit Report", level=0)
    for run in title.runs:
        run.font.color.rgb = RGBColor(0x2D, 0x2D, 0x2D)

    # 2. Metadata
    meta = doc.add_paragraph()
    meta.add_run("Generated at: ").bold = True
    meta.add_run(datetime.now().strftime("%Y-%m-%d %H:%M"))
    
    meta = doc.add_paragraph()
    meta.add_run(f"Document Type: {audit.get('documentType', 'Unknown')}")
    meta.add_run(" | ").bold = False
    meta.add_run(f"Jurisdiction: {audit.get('jurisdiction', {}).get('state', 'Unknown')}")

    # 3. Risk Summary
    doc.add_heading("Audit Summary", level=2)
    risk_p = doc.add_paragraph()
    run = risk_p.add_run(f"Overall Risk Score: {audit.get('riskScore', 0)}/100")
    run.bold = True
    run.font.size = Pt(12)

    # 4. The Document (Redlined/Final)
    doc.add_heading("Processed Document", level=2)
    body = doc.add_paragraph(text)
    body.style = "Normal"

    # 5. Detailed Findings
    findings = audit.get("findings", [])
    if findings:
        doc.add_heading("Detailed Audit Findings", level=2)
        for f in findings:
            p = doc.add_paragraph(style="List Bullet")
            
            # Header: Title + Severity
            run_title = p.add_run(f"{f.get('title')} ")
            run_title.bold = True
            
            run_sev = p.add_run(f"[{f.get('severity', '').upper()}]")
            run_sev.font.color.rgb = get_color(f.get('severity', 'info'))
            
            # Finding description
            p.add_run(f"\n{f.get('finding', '')}")
            
            # Citation
            cite_run = p.add_run(f"\nSource: {f.get('statute', 'N/A')}")
            cite_run.italic = True
            cite_run.font.size = Pt(9)

    # Final footer
    doc.add_paragraph("\n")
    foot = doc.add_paragraph("Generated by Suite AI Document Intelligence Platform.")
    foot.runs[0].font.size = Pt(8)
    foot.runs[0].font.color.rgb = RGBColor(0x88, 0x88, 0x88)

    buf = BytesIO()
    doc.save(buf)
    return buf.getvalue()

if __name__ == "__main__":
    try:
        input_path = sys.argv[1]
        with open(input_path, 'r') as f:
            data = json.load(f)
        
        docx_bytes = build_docx(data)
        print(base64.b64encode(docx_bytes).decode('utf-8'))
    except Exception as e:
        print(f"Error: {str(e)}", file=sys.stderr)
        sys.exit(1)
