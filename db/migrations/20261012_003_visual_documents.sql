-- ============================================================================
-- Visual Documents & reusable design templates
-- Created: 2026-10-12
--
-- WHAT THIS IS
--   The "Visual Document" replaces the Documents panel in the Suite aside. It
--   is the artefact a discussion assembles into: a web page / deck of slides,
--   optionally with generated imagery.
--
-- WHY IT IS NOT "just generate an image with an AI model"
--   The PFP print-template use case (photo-booth overlays: ornate frame, N
--   empty photo windows, exact school/date text) is the hard case, and it
--   breaks under naive image generation:
--     - an image model cannot render "West Potomac High School" reliably;
--       it garbles letterforms, which is unacceptable on a customer print.
--     - it redraws the ornament differently every week, so there is no
--       consistent house style across a season of events.
--   So generation is split by ROLE, which is the same split Canva's Autofill
--   API makes:
--     - ORNAMENT / FRAME  -> a reusable template asset, created once, reused.
--                            Never regenerated.
--     - TEXT              -> rendered exactly with a real font.
--     - PHOTOS            -> real event photos composited into the windows.
--     - CONCEPTUAL ART    -> generated (MuAPI nano-banana / wan), only where a
--                            slide is genuinely illustrative.
--   One template + new data = a new product. That is the whole point.
--
-- SAFE TO RE-RUN. Forward-only; no DROP of anything.
-- ============================================================================

CREATE SCHEMA IF NOT EXISTS app;

-- ── 1. design_templates — the reusable skeleton ──────────────────────────
-- One row per reusable visual design (a print overlay, a deck layout, a
-- briefing frame). Created once, reused indefinitely. This is what stops the
-- weekly job from drifting.
CREATE TABLE IF NOT EXISTS app.design_templates (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id       UUID NOT NULL DEFAULT '00000000-0000-0000-0000-000000000000'::uuid,
    slug            TEXT NOT NULL,
    name            TEXT NOT NULL,
    kind            TEXT NOT NULL DEFAULT 'overlay'
                    CHECK (kind IN ('overlay','deck','briefing','web','social')),
    -- Canvas geometry. 2-up print sheets are ~850x1100; a slide is 1920x1080.
    width_px        INTEGER NOT NULL DEFAULT 850,
    height_px       INTEGER NOT NULL DEFAULT 1100,
    -- The reusable artwork: a PNG with the photo windows knocked out to alpha.
    -- NULL for pure-web templates, which have no raster artwork.
    template_url    TEXT,
    -- Recurring style knobs so a new deck inherits the house look rather than
    -- re-specifying colours every time.
    style           JSONB NOT NULL DEFAULT '{}'::jsonb,
    -- Optional default copy, overridable per instance.
    defaults        JSONB NOT NULL DEFAULT '{}'::jsonb,
    description     TEXT,
    tags            TEXT[] NOT NULL DEFAULT '{}',
    is_active       BOOLEAN NOT NULL DEFAULT true,
    -- Provenance: was this authored by a human, or generated by an agent?
    -- An agent-authored template must still be reviewed by a human before it is
    -- used for customer-facing print, and `approved_by` is how that is recorded.
    created_by      TEXT NOT NULL DEFAULT 'unknown',
    approved_by     TEXT,
    approved_at     TIMESTAMPTZ,
    usage_count     INTEGER NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT design_templates_slug_key UNIQUE (tenant_id, slug)
);

COMMENT ON COLUMN app.design_templates.template_url IS
  'Reusable frame artwork with photo windows transparent. Never regenerate this '
  'per instance — a redrawn ornament breaks visual consistency across a season.';

COMMENT ON COLUMN app.design_templates.approved_by IS
  'NULL means nobody has signed this off. Agent-authored templates must be '
  'approved by a human before customer-facing print use.';

-- ── 2. template_fields — the autofill contract ───────────────────────────
-- This is the Canva Autofill pattern. A template declares named, typed slots;
-- an instance fills them. Adding a field here is all it takes to make a new
-- slot fillable — no code change.
CREATE TABLE IF NOT EXISTS app.template_fields (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    template_id     UUID NOT NULL REFERENCES app.design_templates(id) ON DELETE CASCADE,
    field_key       TEXT NOT NULL,          -- e.g. PHOTO_1, TITLE, SUBTITLE
    field_type      TEXT NOT NULL
                    CHECK (field_type IN ('image','video','text','chart','sheet')),
    label           TEXT,
    -- Placement within the canvas, so a renderer needs no extra config.
    x               INTEGER NOT NULL DEFAULT 0,
    y               INTEGER NOT NULL DEFAULT 0,
    w               INTEGER NOT NULL DEFAULT 100,
    h               INTEGER NOT NULL DEFAULT 100,
    -- Text field styling.
    font_family     TEXT,
    font_size       INTEGER,
    font_color      TEXT,
    align           TEXT DEFAULT 'center' CHECK (align IN ('left','center','right')),
    -- Whether a missing value is an error or just leaves the slot blank.
    required        BOOLEAN NOT NULL DEFAULT false,
    default_value   TEXT,
    sort_order      INTEGER NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT template_fields_key_unique UNIQUE (template_id, field_key)
);

COMMENT ON TABLE app.template_fields IS
  'Named typed slots on a template (the autofill contract). Instances supply '
  'values keyed by field_key; unset optional fields render blank rather than '
  'failing the whole document.';

-- ── 3. visual_documents — one assembled artefact ─────────────────────────
CREATE TABLE IF NOT EXISTS app.visual_documents (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id       UUID NOT NULL DEFAULT '00000000-0000-0000-0000-000000000000'::uuid,
    session_id      TEXT NOT NULL,
    template_id     UUID REFERENCES app.design_templates(id) ON DELETE SET NULL,
    title           TEXT NOT NULL DEFAULT 'Untitled Visual Document',
    kind            TEXT NOT NULL DEFAULT 'web'
                    CHECK (kind IN ('web','deck','overlay','briefing')),
    status          TEXT NOT NULL DEFAULT 'draft'
                    CHECK (status IN ('draft','assembling','ready','published','archived')),
    -- The filled slot values, keyed by field_key.
    data            JSONB NOT NULL DEFAULT '{}'::jsonb,
    -- Rendered output (image / pdf URL) once produced.
    render_url      TEXT,
    render_kind     TEXT,
    -- Provenance of each generated image: model, cost, prompt. Lets an agent
    -- and a human answer "why is this slide 4 cents" and stop runaway spend.
    generation_log  JSONB NOT NULL DEFAULT '[]'::jsonb,
    estimated_cost  NUMERIC(10,4) NOT NULL DEFAULT 0,
    created_by      TEXT NOT NULL DEFAULT 'unknown',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_visual_documents_session
  ON app.visual_documents(tenant_id, session_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_visual_documents_status
  ON app.visual_documents(tenant_id, status);

COMMENT ON COLUMN app.visual_documents.generation_log IS
  'Per-asset provenance: {field_key, model, prompt, cost_usd, request_id}. '
  'Image generation costs real money, so every generated asset is accounted.';

-- ── 4. visual_slides — sections of a deck / briefing ────────────────────
CREATE TABLE IF NOT EXISTS app.visual_slides (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    document_id     UUID NOT NULL REFERENCES app.visual_documents(id) ON DELETE CASCADE,
    slide_index     INTEGER NOT NULL,
    title           TEXT,
    -- Slide body. 'markdown' renders rich text; 'viz' renders a chart when
    -- `chart_spec` is set; 'image' shows a generated or uploaded asset.
    layout          TEXT NOT NULL DEFAULT 'prose'
                    CHECK (layout IN ('prose','title','bullets','viz','image','quote','image_split')),
    body_md         TEXT,
    chart_spec      JSONB,
    image_url       TEXT,
    image_alt       TEXT,
    -- Which generation model produced image_url, if generated.
    image_model     TEXT,
    image_prompt    TEXT,
    image_cost_usd  NUMERIC(10,4),
    notes           TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT visual_slides_index_unique UNIQUE (document_id, slide_index)
);

CREATE INDEX IF NOT EXISTS idx_visual_slides_doc ON app.visual_slides(document_id, slide_index);

-- ── 5. Retention — this is why delete exists ─────────────────────────────
-- Visual documents accumulate: a busy session can make one per exchange, and
-- each may hold generated assets that cost money. Retention is explicit and
-- countable rather than an unbounded pile.
CREATE TABLE IF NOT EXISTS app.visual_document_retention (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id       UUID NOT NULL DEFAULT '00000000-0000-0000-0000-000000000000'::uuid,
    keep_days       INTEGER NOT NULL DEFAULT 90,
    max_documents   INTEGER NOT NULL DEFAULT 500,
    -- Never auto-delete anything a human has pinned or exported.
    archive_instead BOOLEAN NOT NULL DEFAULT true,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT visual_retention_tenant_key UNIQUE (tenant_id)
);

INSERT INTO app.visual_document_retention (tenant_id)
VALUES ('00000000-0000-0000-0000-000000000000')
ON CONFLICT (tenant_id) DO NOTHING;

-- ── 6. updated_at triggers ───────────────────────────────────────────────
CREATE OR REPLACE FUNCTION app.touch_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'design_templates','visual_documents','visual_slides','visual_document_retention'
  ] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_touch ON app.%1$I', t);
    EXECUTE format(
      'CREATE TRIGGER trg_%1$s_touch BEFORE UPDATE ON app.%1$I '
      'FOR EACH ROW EXECUTE FUNCTION app.touch_updated_at()', t);
  END LOOP;
END $$;